/**
 * 智能聚合搜索与动态资源合成器
 * 模拟PanSou/PanHub核心引擎：针对任意关键词都能检索或动态匹配对应网盘的结构化资源
 */
export function searchResources(
  keyword: string,
  panType: PanType | 'all',
  category: ResourceCategory,
  resolution: string,
  sortBy: 'match' | 'latest' | 'size' | 'views'
): ResourceItem[] {
  let list = [...INITIAL_RESOURCES];

  // 1. 如果有输入关键词，先在精选库中模糊匹配
  if (keyword.trim()) {
    const kw = keyword.trim().toLowerCase();
    const matched = list.filter(item => 
      item.title.toLowerCase().includes(kw) ||
      item.tags.some(t => t.toLowerCase().includes(kw)) ||
      item.description.toLowerCase().includes(kw)
    );

    // 如果库中有匹配项，使用匹配项；若没有，动态模拟生成3~5个不同网盘的真实结果，满足全网搜索需求
    if (matched.length > 0) {
      list = matched;
    } else {
      // 动态合成跨网盘结果
      list = generateDynamicPanResults(keyword.trim());
    }
  }

  // 2. 网盘过滤
  if (panType !== 'all') {
    list = list.filter(item => item.panType === panType);
  }

  // 3. 分类过滤
  if (category !== 'all') {
    list = list.filter(item => item.category === category);
  }

  // 4. 清晰度过滤
  if (resolution && resolution !== 'all') {
    list = list.filter(item => item.resolution === resolution);
  }

  // 5. 排序
  list.sort((a, b) => {
    if (sortBy === 'latest') {
      return a.id.localeCompare(b.id);
    }
    if (sortBy === 'size') {
      const getNum = (s: string) => parseFloat(s) || 0;
      return getNum(b.size) - getNum(a.size);
    }
    if (sortBy === 'views') {
      return b.viewsCount - a.viewsCount;
    }
    // match
    return b.sharesCount - a.sharesCount;
  });

  return list;
}

